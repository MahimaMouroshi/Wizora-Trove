import { Router } from 'express';
import Joi from 'joi';
import { protect, adminOnly } from '../middleware/auth.js';
import { validate } from '../middleware/validate.js';
import { asyncHandler } from '../utils/asyncHandler.js';
import { stats, listBooks, createBook, updateBook, deleteBook, activateMembership, updateRequest, listUsers, updateUser, activeRentals, listListings } from '../controllers/adminController.js';
import { listOrders, updateOrder } from '../controllers/orderController.js';
import { listRestorations, updateRestoration } from '../controllers/restorationController.js';
import { listBlindDates, updateBlindDate, listAllOptions, createOption, deleteOption } from '../controllers/blindDateController.js';

const router = Router();
router.use(protect, adminOnly);
router.get('/stats', asyncHandler(stats));
router.get('/users', asyncHandler(listUsers));
router.patch('/users/:id', asyncHandler(updateUser));
router.get('/rentals', asyncHandler(activeRentals));
router.get('/books', asyncHandler(listBooks));
router.post('/books', asyncHandler(createBook));
router.patch('/books/:id', asyncHandler(updateBook));
router.delete('/books/:id', asyncHandler(deleteBook));
router.post('/memberships/activate', validate(Joi.object({ userId: Joi.string().required(), plan: Joi.string().valid('3_month', '6_month', '12_month').required(), securityDeposit: Joi.number().min(0).default(0), paymentStatus: Joi.string().valid('unpaid', 'pending', 'paid').default('paid') })), asyncHandler(activateMembership));
router.get('/orders', asyncHandler(listOrders));
router.patch('/orders/:id', asyncHandler(updateOrder));
router.get('/restorations', asyncHandler(listRestorations));
router.patch('/restorations/:id', asyncHandler(updateRestoration));
router.get('/blind-date', asyncHandler(listBlindDates));
router.patch('/blind-date/:id', asyncHandler(updateBlindDate));
router.get('/blind-date/options', asyncHandler(listAllOptions));
router.post('/blind-date/options', validate(Joi.object({ packageCategory: Joi.string().valid('Basic', 'Moderate', 'Premium', 'Luxury').required(), genre: Joi.string().required(), language: Joi.string().valid('Bangla', 'English').required(), title: Joi.string().max(150).required() })), asyncHandler(createOption));
router.delete('/blind-date/options/:id', asyncHandler(deleteOption));
router.get('/decutler', asyncHandler(listListings));
export default router;