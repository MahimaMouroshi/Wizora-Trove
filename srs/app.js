import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/authRoutes.js';
import profileRoutes from './routes/profileRoutes.js';
import libraryRoutes from './routes/libraryRoutes.js';
import requestRoutes from './routes/requestRoutes.js';
import ratingRoutes from './routes/ratingRoutes.js';
import marketplaceRoutes from './routes/marketplaceRoutes.js';
import restorationRoutes from './routes/restorationRoutes.js';
import orderRoutes from './routes/orderRoutes.js';
import blindDateRoutes from './routes/blindDateRoutes.js';
import membershipRoutes from './routes/membershipRoutes.js';
import adminRoutes from './routes/adminRoutes.js';
import { notFound, errorHandler } from './middleware/error.js';
import booksRouter from './routes/books.js';
import { uploadDir } from './middleware/upload.js';
import cartRouter from './routes/cart.js';


const app = express();
app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL?.split(',').map(s => s.trim()) || '*', credentials: false }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: true }));
app.use(morgan(process.env.NODE_ENV === 'production' ? 'combined' : 'dev'));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: true, legacyHeaders: false }));
app.get('/api/health', (req, res) => res.json({ success: true, service: 'Wizora Trove API', status: 'ok', time: new Date().toISOString() }));
app.use('/api/auth', authRoutes);
app.use('/api/profile', profileRoutes);
app.use('/api/library', libraryRoutes);
app.use('/api/requests', requestRoutes);
app.use('/api/ratings', ratingRoutes);
app.use('/api/decutler', marketplaceRoutes);
app.use('/api/restoration', restorationRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/blind-date', blindDateRoutes);
app.use('/api/membership', membershipRoutes);
app.use('/api/admin', adminRoutes);
app.use('/uploads', express.static(uploadDir));
app.use('/api/shop/books', booksRouter);
app.use('/api/shop/cart', cartRouter);
app.use(notFound);
app.use(errorHandler);
export default app;
